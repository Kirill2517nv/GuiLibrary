// ============================================================
// Task_0. Движение тела, брошенного под углом к горизонту.
//
// Тело вылетает из точки (x_0, y_0) со скоростью V под углом alpha.
// Координаты в момент времени t считаются по формулам кинематики:
//
//     x(t) = x_0 + V * cos(alpha) * t
//     y(t) = y_0 + V * sin(alpha) * t - g * t^2 / 2
//
// Цель: подобрать скорость и угол так, чтобы тело попало в мишень.
//
// Управление: меняем параметры слева, нажимаем Restart — тело летит заново.
// ============================================================

#include "gui_library.h"
#include <vector>
#include <cmath>

// ------------------------------------------------------------
// Постоянные величины задачи
// ------------------------------------------------------------

const float G  = 9.8f;   // ускорение свободного падения, м/с^2
const float PI = 3.14159265f;

// Мишень — отрезок между двумя точками. Точки можно задать любые:
// мишень получится вертикальной, горизонтальной или наклонной.
const float TARGET_X1 = 8.5f,  TARGET_Y1 = 3.0f;   // один конец мишени, м
const float TARGET_X2 = 10.5f, TARGET_Y2 = 3.5f;   // другой конец мишени, м

// Из скольких точек состоит мишень. Точек должно быть много, чтобы между
// соседними не оставалось «дырок», сквозь которые тело пролетит незамеченным.
const int TARGET_POINTS = 50;

// Насколько близко надо подлететь к мишени, чтобы засчитать попадание, м.
// Это радиус тела: чем он больше, тем легче попасть.
const float HIT_RADIUS = 0.15f;

// Имя графика: используется и при создании, и при рисовании
const char* PLOT = "Movement at an angle";

// ------------------------------------------------------------
// Мишень: набор точек. По этим же точкам мы её и рисуем, и проверяем попадание
// ------------------------------------------------------------

std::vector<float> target_x;  // координаты X точек мишени
std::vector<float> target_y;  // координаты Y точек мишени

// Земля — линия y = 0 от левого до правого края графика
std::vector<float> ground_x = {-0.1f, 10.f};
std::vector<float> ground_y = { 0.0f,  0.f};

// Расставляем точки равномерно вдоль отрезка мишени
void make_target() {
    target_x.clear();
    target_y.clear();
    for (int i = 0; i <= TARGET_POINTS; i++) {
        float k = (float)i / TARGET_POINTS;   // доля пути вдоль мишени: от 0 до 1
        target_x.push_back(TARGET_X1 + k * (TARGET_X2 - TARGET_X1));
        target_y.push_back(TARGET_Y1 + k * (TARGET_Y2 - TARGET_Y1));
    }
}

// ------------------------------------------------------------
// Состояние тела (меняется во время полёта)
// ------------------------------------------------------------

float t;                // время от начала полёта, с
float x, y;             // текущие координаты тела, м

float V, alpha;         // начальная скорость (м/с) и угол броска (градусы)
float x_0, y_0;         // точка старта, м

bool flying = false;    // тело ещё летит?
bool hit    = false;    // попали в мишень?

// Перевод градусов в радианы: sin и cos работают с радианами
float radians(float degrees) {
    return degrees * PI / 180.f;
}

// ------------------------------------------------------------
// Проверка попадания.
//
// Мишень — это набор точек. Тело попало, если оно подлетело хотя бы к одной
// из них ближе, чем на HIT_RADIUS. Расстояние между двумя точками считаем
// по теореме Пифагора: d = sqrt(dx^2 + dy^2).
//
// Важно: за один шаг тело пролетает V * dt метров. Если сделать шаг по времени
// слишком большим, тело перепрыгнет мишень и попадание не засчитается.
// ------------------------------------------------------------

bool touches_target(float body_x, float body_y) {
    for (size_t i = 0; i < target_x.size(); i++) {
        float dx = body_x - target_x[i];
        float dy = body_y - target_y[i];
        float distance = sqrt(dx * dx + dy * dy);

        if (distance < HIT_RADIUS)
            return true;
    }
    return false;
}

// ------------------------------------------------------------
// Кнопка Restart: считываем параметры из окна и начинаем полёт заново
// ------------------------------------------------------------

void restart() {
    V     = get_float_param("Velocity");
    alpha = get_float_param("Angle");
    x_0   = get_float_param("x_0");
    y_0   = get_float_param("y_0");

    t = 0.f;
    x = x_0;
    y = y_0;

    flying = true;
    hit    = false;

    // стираем старую траекторию и ставим в начало точку старта
    clear_plot_history(PLOT);
    add_plot_history_point(PLOT, x, y, "Trajectory", BLUE, 1.f, 2000);

    set_bool_param("Pause", false);
}

// ------------------------------------------------------------
// Основная расчётная функция: библиотека вызывает её каждый кадр
// ------------------------------------------------------------

void calculation_function() {
    bool pause = get_bool_param("Pause");

    // считаем следующий шаг, только если тело летит и пауза не нажата
    if (flying && !pause) {
        float dt = get_float_param("dt");

        t += dt;
        x = x_0 + V * cos(radians(alpha)) * t;
        y = y_0 + V * sin(radians(alpha)) * t - G * t * t / 2.f;

        // попали в мишень — полёт закончен
        if (touches_target(x, y)) {
            hit    = true;
            flying = false;
        }

        // тело коснулось земли — полёт тоже закончен
        if (y <= 0.f) {
            y = 0.f;
            flying = false;
        }

        add_plot_history_point(PLOT, x, y, "Trajectory", BLUE, 1.f, 2000);
    }

    // --- рисуем картину заново каждый кадр ---
    // clear_plot убирает объекты прошлого кадра, накопленная траектория остаётся
    clear_plot(PLOT);

    // земля
    add_plot_line(PLOT, ground_x, ground_y, "Ground", GREEN, 1.f);

    // мишень — те же точки, по которым проверяем попадание
    add_plot_line(PLOT, target_x, target_y, "Target", WHITE, 3.f);

    // само тело
    add_plot_point(PLOT, x, y, "Body", RED, 5.f);

    // отметка попадания
    if (hit)
        add_plot_point(PLOT, x, y, "Hit!", YELLOW, 10.f);
}

// ------------------------------------------------------------
// Точка входа
// ------------------------------------------------------------

int main() {
    // окно приложения
    if (!init_gui_library("Task_0: Movement at an angle", 1200, 800)) return -1;

    // параметры: их видно слева и можно менять во время работы
    add_bool_param("Pause", false);
    add_button_param("Restart", restart);
    add_float_param("Velocity", 8.0f);   // начальная скорость, м/с
    add_float_param("Angle", 30.0f);     // угол броска, градусы
    add_float_param("dt", 0.01f);        // шаг по времени, с
    add_float_param("x_0", 0.0f);        // старт по горизонтали, м
    add_float_param("y_0", 3.0f);        // старт по высоте, м

    // график: границы осей по X и Y, затем размер полотна в пикселях
    create_plot(PLOT, -0.1f, 11.f, -0.1f, 5.f, 800, 700);

    // готовим мишень и первый полёт
    make_target();
    restart();

    // расчётная функция вызывается каждый кадр
    set_calculation_function(calculation_function);

    // параметры слева, график справа
    set_auto_layout();

    // главный цикл: считай -> рисуй
    run_gui_library();
    return 0;
}
